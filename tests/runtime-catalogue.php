<?php
/** Run only on a disposable WordPress site with the controller active. */
if (!defined('ABSPATH') || !defined('TNUC_VERSION')) { throw new RuntimeException('Activate TN Update Controller on a disposable WordPress site.'); }
wp_set_current_user(1);
function runtime_assert($condition, $message) { if (!$condition) { throw new RuntimeException($message); } echo "PASS: $message\n"; }
$root = getenv('TNUC_TEST_REPO');
if (!$root || !is_file($root . '/catalogue-registry.json')) { throw new RuntimeException('Set TNUC_TEST_REPO to the repository root.'); }
$registry = json_decode((string) file_get_contents($root . '/catalogue-registry.json'), true);
$catalogs = tnuc_catalogs();
runtime_assert(count($catalogs) === 5 && count($catalogs['techn-27']['plugins']) === 20 && count($catalogs['techn-25']['plugins']) === 8 && count($catalogs['techn-26']['plugins']) === 25 && count($catalogs['alphasys-26']['plugins']) === 23 && count($catalogs['fusion-26']['plugins']) === 24, 'five bundled catalogs and their memberships load');
$original_selection = tnuc_catalog_selection();
tnuc_put('catalog_selection', tnuc_default_catalog_selection());
runtime_assert(tnuc_catalog_selection() === ['techn-27'], 'latest Techn catalog is selected by default');
$cached_registry = tnuc_get('catalog_registry', null);
$old_registry = $registry;
unset($old_registry['revision']);
$old_registry['catalogs'] = array_values(array_filter($old_registry['catalogs'], static function ($catalog) { return !in_array($catalog['id'], ['techn-25', 'techn-27'], true); }));
tnuc_put('catalog_registry', $old_registry);
runtime_assert(count(tnuc_catalogs()) === 5, 'new bundled catalog revision takes precedence over an older site cache');
tnuc_put('catalog_registry', $cached_registry);
$future_registry = $registry;
$future_techn = $future_registry['catalogs'][0];
$future_techn['id'] = 'techn-28'; $future_techn['release'] = '28'; $future_techn['year'] = '28'; $future_techn['name'] = 'Techn';
$future_registry['catalogs'][] = $future_techn;
$future_registry['revision'] = 4;
tnuc_put('catalog_registry', $future_registry);
runtime_assert(tnuc_default_catalog_selection() === ['techn-28'], 'new installations default to the latest current Techn edition');
tnuc_put('catalog_registry', $cached_registry);
$selection = tnuc_save_catalog_selection(['techn-26', 'alphasys-26', 'fusion-26']);
runtime_assert(!is_wp_error($selection) && tnuc_catalog_selection() === ['techn-26', 'alphasys-26', 'fusion-26'], 'site catalog selections persist');
set_current_screen(is_multisite() ? 'plugins-network' : 'plugins');
global $submenu;
unset($submenu['plugins.php']);
do_action(is_multisite() ? 'network_admin_menu' : 'admin_menu');
runtime_assert(array_slice(array_column($submenu['plugins.php'] ?? [], 2), -5) === ['tnuc-techn', 'tnuc-alphasys', 'tnuc-fusion', 'tnuc-other', 'tnuc'], 'one submenu per selected collection; Collections is last');
$network_calls = 0;
$deny = static function ($pre, $args, $url) use (&$network_calls) { $network_calls++; return new WP_Error('unexpected_http', 'Rendering made an HTTP request.'); };
add_filter('pre_http_request', $deny, 10, 3);
ob_start(); tnuc_hub_render_registry(); $registry_html = ob_get_clean();
runtime_assert(strpos($registry_html, 'Collections Catalog') !== false && strpos($registry_html, '<th scope="col">Release</th>') !== false && substr_count($registry_html, 'type="checkbox"') === 5, 'collection catalog lists all five releases with checkboxes');
runtime_assert(strpos($registry_html, '<th scope="col">Type</th>') !== false && substr_count($registry_html, '>Hosted</td>') === 4 && strpos($registry_html, '>Mirrored</td>') !== false, 'catalog list shows Hosted and Mirrored types');
runtime_assert(strpos($registry_html, '<th scope="col">Last updated</th>') !== false && substr_count($registry_html, '>15 Nov 2026</td>') === 5, 'catalog list shows each catalog last updated date');
runtime_assert(strpos($registry_html, 'catalogs/techn-25.md') !== false && strpos($registry_html, 'catalogs/techn-27.md') !== false && strpos($registry_html, 'target="_blank" rel="noopener noreferrer"') !== false, 'catalog plugin lists open on GitHub in a new tab');
runtime_assert(tnuc_legacy_catalog_target('tnuc-techn') === '' && tnuc_legacy_catalog_target('tnuc-fusion') === '' && tnuc_legacy_catalog_target('tn-other-plugins') === 'tnuc-other', 'collection pages stay put and Other old URL redirects');
runtime_assert(tnuc_legacy_catalog_target('tnuc-techn-26') === 'tnuc-techn' && tnuc_legacy_catalog_target('tnuc-missing-25') === 'tnuc', 'old release pages redirect to their collection or the registry');
$legacy_view = tnuc_hub_dispatch('view', ['screen' => 'tnuc-techn', 'tab' => 'installed']);
runtime_assert(!is_wp_error($legacy_view) && $legacy_view['screen'] === 'tnuc-techn' && strpos($legacy_view['html'], 'Techn Plugins') !== false, 'Techn browser session refreshes the collection screen');
$older_view = tnuc_hub_dispatch('view', ['catalog' => 'fusion-26', 'tab' => 'catalogue']);
runtime_assert(!is_wp_error($older_view) && $older_view['screen'] === 'tnuc-fusion' && strpos($older_view['html'], 'Fusion Plugins') !== false, 'older release picker session can complete its refresh');
$_GET['page'] = 'tnuc-fusion'; $_GET['tab'] = 'catalog';
ob_start(); tnuc_hub_render_admin(); $html = ob_get_clean();
runtime_assert(strpos($html, 'Fusion Plugins') !== false && strpos($html, 'Fusion 26 Plugins') === false && strpos($html, '<dialog') !== false && strpos($html, 'id="tnuc-catalog"') === false, 'Fusion screen uses the collection name and shared modal');
runtime_assert(strpos($html, 'Techn Plugins') === false && strpos($html, 'AlphaSys Plugins') === false, 'Fusion screen is scoped to its catalog');
$_GET['page'] = 'tnuc-other';
ob_start(); tnuc_hub_render_admin(); $html = ob_get_clean();
runtime_assert(strpos($html, 'Other Plugins') !== false && strpos($html, '<dialog') !== false, 'Other screen always renders');
runtime_assert(is_wp_error(tnuc_save_catalog_selection([])) && is_wp_error(tnuc_save_catalog_selection(['fusion-26'])), 'at least one Techn release is required');
runtime_assert(tnuc_catalog_selection() === ['techn-26', 'alphasys-26', 'fusion-26'], 'invalid selection does not alter saved releases');
tnuc_put('catalog_selection', ['fusion-26']);
runtime_assert(tnuc_catalog_selection() === ['techn-27', 'fusion-26'], 'older site selection without Techn receives the current Techn release');
tnuc_put('catalog_selection', ['techn-26', 'alphasys-26', 'fusion-26']);
tnuc_save_catalog_selection(['techn-26', 'alphasys-26', 'fusion-26']);
runtime_assert($network_calls === 0, 'normal page render makes no HTTP requests');
remove_filter('pre_http_request', $deny, 10);
$registry_response = static function ($pre, $args, $url) use ($registry) {
    if (strtok($url, '?') !== TNUC_REGISTRY_URL) { return $pre; }
    return ['response' => ['code' => 200], 'headers' => [], 'body' => wp_json_encode($registry)];
};
add_filter('pre_http_request', $registry_response, 10, 3);
$check = tnuc_hub_check();
remove_filter('pre_http_request', $registry_response, 10);
runtime_assert(!is_wp_error($check) && in_array($check['status'], ['complete', 'partial', 'controller_update'], true), 'manual check reaches published source feeds');
runtime_assert(count((array) tnuc_get('as_catalogue')) === 23 && count((array) tnuc_get('fusion_mirror')) === 13, 'AlphaSys and Fusion package feeds cache their registered releases');
runtime_assert(isset(tnuc_hub_items()['fusion:disable-comments']), 'Fusion membership remains available after check');
$two_editions = $registry;
$two_editions['catalogs'][] = ['id' => 'editorial-26', 'collection' => 'editorial', 'release' => '26', 'name' => 'Editorial', 'status' => 'current', 'plugins' => []];
$two_editions['revision'] = 4;
tnuc_put('catalog_registry', $two_editions);
runtime_assert(!is_wp_error(tnuc_save_catalog_selection(['techn-25', 'techn-26', 'editorial-26'])), 'two Techn editions and a future catalog can be selected together');
unset($submenu['plugins.php']);
do_action(is_multisite() ? 'network_admin_menu' : 'admin_menu');
$menu_slugs = array_column($submenu['plugins.php'] ?? [], 2);
runtime_assert(array_slice($menu_slugs, -4) === ['tnuc-techn', 'tnuc-editorial', 'tnuc-other', 'tnuc'], 'selected releases share a collection submenu; Other and Collections Catalog are last');
runtime_assert(count(array_filter(tnuc_hub_items(), static function ($item) { return $item['catalog'] === 'techn' && $item['entry']['id'] === 'tn-update-controller'; })) === 1, 'two selected Techn releases show the controller once');
tnuc_put('catalog_registry', $cached_registry);
unset($_GET['tab'], $_GET['page']);
tnuc_put('catalog_selection', $original_selection);
